func TestPublisherDispatch(t *testing.T) {
	obs, _ := testObservability(t)
	var stored *Task
	store := &storeStub{enqueue: func(_ context.Context, task *Task) error { stored = task; return nil }}
	publisher, err := NewPublisher(Definition[string]{Queue: "mail", MessageType: "message", Version: 1}, store, obs)
	if err != nil {
		t.Fatal(err)
	}
	id, err := publisher.Publish(context.Background(), "hello")
	if err != nil || id == "" || stored.Type != "message.v1" || string(stored.Payload) != `"hello"` {
		t.Fatalf("publish: %s %v %+v", id, err, stored)
	}
	at := time.Now().Add(time.Hour)
	id, err = publisher.PublishWith(context.Background(), "later", PublishOptions{ID: "stable", AvailableAt: at})
	if err != nil || id != "stable" || !stored.AvailableAt.Equal(at) {
		t.Fatalf("scheduled: %s %v %+v", id, err, stored)
	}
}

func TestPublisherWireBindings(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	module := "github.com/jaggerzhuang1994/kratos-foundation/v2"
	for _, name := range []string{"go.mod", "go.sum", "assembly.go", "assembly_test.go", "wire.go"} {
		source := filepath.Join("testdata", "wireassembly", name)
		if name == "go.mod" || name == "go.sum" {
			source = filepath.Join(root, name)
		}
		data, err := os.ReadFile(source)
		if err != nil {
			t.Fatal(err)
		}
		if name == "go.mod" {
			content := strings.Replace(string(data), "module "+module, "module wireassembly", 1)
			content += "\nrequire " + module + " v2.0.0\nreplace " + module + " => " + strconv.Quote(root) + "\n"
			data = []byte(content)
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	for _, args := range [][]string{{"tool", "wire", "."}, {"test", "-race", "-count=1", "."}} {
		cmd := exec.CommandContext(ctx, "go", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GOWORK=off")
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("go %v: %v\n%s", args, err, output)
		}
	}
	generated, err := os.ReadFile(filepath.Join(dir, "wire_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, call := range []string{"Code generated by Wire", "newEmailQueue(", "newBotQueue("} {
		if !strings.Contains(string(generated), call) {
			t.Fatalf("generated injector missing %s", call)
		}
	}
}

func TestPublisherRejectsBeforeStorage(t *testing.T) {
	obs, _ := testObservability(t)
	failure := errors.New("invalid message")
	for _, definition := range []Definition[string]{
		{Queue: "q", MessageType: "m", Version: 1, Validate: func(string) error { return failure }},
		{Queue: "q", MessageType: "m", Version: 1, Codec: stringCodec{err: failure}},
	} {
		publisher, err := NewPublisher(definition, &storeStub{}, obs)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := publisher.Publish(context.Background(), "hello"); !errors.Is(err, failure) {
			t.Fatal(err)
		}
	}
}
