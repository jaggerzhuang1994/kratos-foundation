package main

import (
	"fmt"
	"strconv"
	"strings"
	"unicode"

	"github.com/go-kratos/kratos/v2/errors"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
)

const (
	errorsPackage = protogen.GoImportPath("github.com/jaggerzhuang1994/kratos-foundation/v2/pkg/errors")
	fmtPackage    = protogen.GoImportPath("fmt")

	minHTTPStatusCode = 100
	maxHTTPStatusCode = 599
)

var commonInitialisms = map[string]string{
	"api":   "API",
	"db":    "DB",
	"grpc":  "GRPC",
	"http":  "HTTP",
	"https": "HTTPS",
	"id":    "ID",
	"ip":    "IP",
	"json":  "JSON",
	"rpc":   "RPC",
	"sql":   "SQL",
	"tcp":   "TCP",
	"tls":   "TLS",
	"udp":   "UDP",
	"uid":   "UID",
	"uri":   "URI",
	"url":   "URL",
	"uuid":  "UUID",
	"xml":   "XML",
}

// generateFile 为含有 Kratos 错误注解的 Proto 枚举生成错误辅助函数。
func generateFile(gen *protogen.Plugin, file *protogen.File, errorStackSkip int) error {
	if len(file.Enums) == 0 {
		return nil
	}
	filename := file.GeneratedFilenamePrefix + "_errors.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	g.P("// Code generated by protoc-gen-kratos-foundation-errors-v2. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	generated, err := generateFileContent(file, g, errorStackSkip)
	if err != nil {
		return fmt.Errorf("generate %s: %w", file.Desc.Path(), err)
	}
	if !generated {
		g.Skip()
	}
	return nil
}

// generateFileContent 生成包声明之后的错误代码，并返回文件是否含有有效错误枚举。
func generateFileContent(
	file *protogen.File,
	g *protogen.GeneratedFile,
	errorStackSkip int,
) (bool, error) {
	if len(file.Enums) == 0 {
		return false, nil
	}

	g.P("// This is a compile-time assertion to ensure that this generated file")
	g.P("// is compatible with the kratos package it is being compiled against.")
	g.P("const _ = ", errorsPackage.Ident("SupportPackageIsVersion1"))
	g.P()
	symbols := buildErrorGoSymbols(g)
	generated := false
	generatedNames := make(map[string]string)
	for _, enum := range file.Enums {
		enumGenerated, err := genErrorsReason(
			g,
			enum,
			generatedNames,
			symbols,
			errorStackSkip,
		)
		if err != nil {
			return false, err
		}
		generated = generated || enumGenerated
	}
	return generated, nil
}

// genErrorsReason 生成一个枚举的错误函数；名称表示 generate errors reason。
func genErrorsReason(
	g *protogen.GeneratedFile,
	enum *protogen.Enum,
	generatedNames map[string]string,
	symbols errorGoSymbols,
	errorStackSkip int,
) (bool, error) {
	defaultCode := 0
	if proto.HasExtension(enum.Desc.Options(), errors.E_DefaultCode) {
		configuredCode := proto.GetExtension(enum.Desc.Options(), errors.E_DefaultCode).(int32)
		defaultCode = int(configuredCode)
	}
	if err := validateHTTPStatusCode(string(enum.Desc.Name()), defaultCode); err != nil {
		return false, err
	}
	ew := errorWrapper{
		Symbols:        symbols,
		ErrorStackSkip: errorStackSkip,
	}
	for _, v := range enum.Values {
		enumCode := defaultCode
		if proto.HasExtension(v.Desc.Options(), errors.E_Code) {
			configuredCode := proto.GetExtension(v.Desc.Options(), errors.E_Code).(int32)
			enumCode = int(configuredCode)
		}
		if err := validateHTTPStatusCode(
			fmt.Sprintf("%s.%s", enum.Desc.Name(), v.Desc.Name()),
			enumCode,
		); err != nil {
			return false, err
		}
		if enumCode == 0 {
			continue
		}
		camelValue := case2Camel(string(v.Desc.Name()))
		if previous, exists := generatedNames[camelValue]; exists {
			return false, fmt.Errorf(
				"enum value %s.%s generates duplicate helper name %q already used by %s",
				enum.Desc.Name(),
				v.Desc.Name(),
				camelValue,
				previous,
			)
		}
		generatedNames[camelValue] = fmt.Sprintf("%s.%s", enum.Desc.Name(), v.Desc.Name())

		comment := v.Comments.Leading.String()
		if comment == "" {
			comment = v.Comments.Trailing.String()
		}
		commentLiteral := commentText(comment)
		err := &errorInfo{
			Value:          string(v.Desc.Name()),
			CamelValue:     camelValue,
			HTTPCode:       enumCode,
			Comment:        commentDoc(commentLiteral),
			CommentLiteral: strconv.Quote(commentLiteral),
			HasComment:     commentLiteral != "",
			NumberValue:    int32(v.Desc.Number()),
			HasFormat:      hasFormatDirective(commentLiteral),
		}
		ew.Errors = append(ew.Errors, err)
	}
	if len(ew.Errors) == 0 {
		return false, nil
	}
	content, err := ew.execute()
	if err != nil {
		return false, err
	}
	g.P(content)

	return true, nil
}

// buildErrorGoSymbols 通过 protogen 生成可能带别名的 Go 标识符，避免生成包内的名称冲突。
func buildErrorGoSymbols(g *protogen.GeneratedFile) errorGoSymbols {
	return errorGoSymbols{
		ErrorType: g.QualifiedGoIdent(errorsPackage.Ident("Error")),
		FromError: g.QualifiedGoIdent(errorsPackage.Ident("FromError")),
		New:       g.QualifiedGoIdent(errorsPackage.Ident("New")),
		Sprintf:   g.QualifiedGoIdent(fmtPackage.Ident("Sprintf")),
		Sprint:    g.QualifiedGoIdent(fmtPackage.Ident("Sprint")),
	}
}

// validateHTTPStatusCode 校验 HTTP 状态码；0 表示该枚举值不生成错误函数。
func validateHTTPStatusCode(name string, code int) error {
	if code == 0 {
		return nil
	}
	if code < minHTTPStatusCode || code > maxHTTPStatusCode {
		return fmt.Errorf(
			"Enum %q HTTP code must be 0 or between %d and %d",
			name,
			minHTTPStatusCode,
			maxHTTPStatusCode,
		)
	}
	return nil
}

// commentText 去除 Proto 注释符号，得到可作为默认错误消息的文本。
func commentText(comment string) string {
	lines := strings.Split(strings.TrimSpace(comment), "\n")
	for index, line := range lines {
		lines[index] = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "//"))
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

// commentDoc 把业务说明转为连续的 Go 行注释，确保它与函数头注释属于同一注释组。
func commentDoc(comment string) string {
	if comment == "" {
		return ""
	}
	lines := strings.Split(comment, "\n")
	for index, line := range lines {
		prefix := "// "
		if index == 0 {
			prefix = "// 业务说明："
		}
		lines[index] = prefix + line
	}
	return strings.Join(lines, "\n")
}

// hasFormatDirective 判断默认消息是否含 fmt 格式化指令，并排除 %% 这类字面百分号。
func hasFormatDirective(value string) bool {
	for index := 0; index < len(value); index++ {
		if value[index] != '%' {
			continue
		}
		if index+1 >= len(value) {
			return false
		}
		if value[index+1] == '%' {
			index++
			continue
		}
		if !unicode.IsSpace(rune(value[index+1])) {
			return true
		}
	}
	return false
}

// case2Camel 把 Proto 枚举名转为 Go 大驼峰名，并保留 HTTP、ID 等常见缩写。
func case2Camel(name string) string {
	strs := strings.Split(name, "_")
	words := make([]string, 0, len(strs))
	for _, w := range strs {
		hasLower := false
		for _, r := range w {
			if unicode.IsLower(r) {
				hasLower = true
				break
			}
		}
		if !hasLower {
			w = strings.ToLower(w)
		}
		if initialism, ok := commonInitialisms[strings.ToLower(w)]; ok {
			w = initialism
		} else if w != "" {
			// Proto 标识符只包含 ASCII 字母，不需要为首字母大写引入完整的自然语言大小写库。
			w = strings.ToUpper(w[:1]) + w[1:]
		}
		words = append(words, w)
	}

	return strings.Join(words, "")
}
